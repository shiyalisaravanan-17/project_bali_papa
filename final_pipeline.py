"""Straight Rows: unified retrospective farm + SDA incident detector.

Reproduces the seven development-stage processing steps without reading labels:
base rules -> fleet grouping -> fault merging -> persistent fault additions ->
severe/localized jamming additions -> peer-relative spoofing additions ->
spoofing deduplication.

Usage (from project directory):
    python final_pipeline.py --mode development
    python final_pipeline.py --mode evaluation
    python submission/validate_submission.py submission.json

Input: fused_features.csv generated by build_features.py and fuse_sda.py.
No train labels are accessed during prediction. Multipath is not yet integrated.
"""
import argparse
import json
from pathlib import Path

import pandas as pd

TR = ("T1", "T2", "T3")
WINDOWS = {
    "development": ("2026-05-04T00:00:00Z", "2026-05-06T00:00:00Z"),
    "evaluation": ("2026-05-06T00:00:00Z", "2026-05-07T00:00:00Z"),
}
ACTIONS = {
    "SPACE_WEATHER": "HALT_OR_DEGRADED_MODE",
    "JAMMING": "HALT_AND_REPORT",
    "SPOOFING": "HALT_CROSSCHECK_AND_REPORT",
    "EQUIPMENT_FAULT": "SERVICE_MACHINE_OTHERS_CONTINUE",
}


def record(cause, start, end, tractors, evidence, confidence=0.6):
    return {
        "start": pd.Timestamp(start).isoformat(),
        "end": pd.Timestamp(end).isoformat(),
        "class": cause,
        "tractors": list(tractors),
        "action": ACTIONS[cause],
        "confidence": float(confidence),
        "evidence": list(evidence),
    }


def segments(mask):
    """Yield consecutive True intervals on a regularly sampled minute index."""
    mask = mask.fillna(False).astype(bool)
    runs = (mask != mask.shift(fill_value=False)).cumsum()
    for _, part in mask[mask].groupby(runs[mask]):
        yield part.index[0], part.index[-1] + pd.Timedelta(minutes=1)


def base_detections(frame, end_limit):
    df = frame.copy()
    df["space_weather"] = ((df.s4 >= .4) & (df.kp >= 5) &
                           (df.affected_fleet_count >= 2))
    # Preserve the legacy development rule. The supplemental jamming
    # detector below separately permits concurrent space weather/jamming.
    df["jamming"] = ((df.mean_cn0 < 36) &
                     (df.affected_fleet_count >= 2) & ~df.space_weather)
    df["spoofing"] = ((df.max_error >= 1) & (df.mean_cn0 >= 38) &
                     (df.rtk_fixed_rate >= .8))
    df["equipment_fault"] = ((df.link_ok_rate < .9) |
                             ((df.mean_cn0 < 35) &
                              (df.affected_fleet_count == 1)))
    rules = {"SPACE_WEATHER": "space_weather", "JAMMING": "jamming",
             "SPOOFING": "spoofing", "EQUIPMENT_FAULT": "equipment_fault"}
    found = []
    for cause, col in rules.items():
        for tractor, group in df.groupby("tractor_id"):
            group = group.sort_values("ts")
            active = group[group[col]]
            if active.empty:
                continue
            blocks = (active.ts.diff().dt.total_seconds().fillna(60) > 60).cumsum()
            for _, ep in active.groupby(blocks):
                if len(ep) < 3:
                    continue
                start, end = ep.ts.iloc[0], min(ep.ts.iloc[-1] + pd.Timedelta(minutes=1), end_limit)
                if end <= start:
                    continue
                evidence = [
                    f"{tractor}: {start.isoformat()} to {end.isoformat()}",
                    f"Mean C/N0: {ep.mean_cn0.mean():.2f} dB-Hz",
                    f"Minimum satellite count: {ep.min_sats.min():.0f}",
                    f"Maximum cross-track error: {ep.max_error.max():.2f} m",
                    f"Mean S4: {ep.s4.mean():.3f}",
                    f"Mean Kp: {ep.kp.mean():.2f}",
                    f"Mean Dst: {ep.dst_nT.mean():.1f} nT",
                    f"Peak simultaneous degraded tractors: {ep.affected_fleet_count.max():.0f}",
                ]
                found.append(record(cause, start, end, [tractor], evidence))
    return sorted(found, key=lambda d: d["start"])


def overlap_ratio(a, b):
    a0, a1 = pd.Timestamp(a["start"]), pd.Timestamp(a["end"])
    b0, b1 = pd.Timestamp(b["start"]), pd.Timestamp(b["end"])
    overlap = max(0, (min(a1, b1) - max(a0, b0)).total_seconds())
    shortest = min((a1 - a0).total_seconds(), (b1 - b0).total_seconds())
    return overlap / shortest if shortest > 0 else 0


def group_fleet(detections):
    """Preserve development implementation's >=70% shorter overlap grouping."""
    groups = []
    for detection in sorted(detections, key=lambda d: d["start"]):
        matched = False
        for group in groups:
            if group["class"] != detection["class"]:
                continue
            if set(group["tractors"]) & set(detection["tractors"]):
                continue
            if overlap_ratio(group, detection) < .7:
                continue
            group["start"] = min(group["start"], detection["start"])
            group["end"] = max(group["end"], detection["end"])
            group["tractors"] = sorted(set(group["tractors"]) | set(detection["tractors"]))
            group["confidence"] = min(group["confidence"], detection["confidence"])
            group["evidence"] = list(dict.fromkeys(group["evidence"] + detection["evidence"]))
            matched = True
            break
        if not matched:
            groups.append({**detection, "tractors": list(detection["tractors"]),
                           "evidence": list(detection["evidence"])})
    return sorted(groups, key=lambda d: d["start"])


def merge_faults(detections):
    source = sorted(detections, key=lambda d: (d["class"], tuple(d["tractors"]), d["start"]))
    merged = []
    for d in source:
        curr = dict(d)
        if (merged and curr["class"] == "EQUIPMENT_FAULT" and
                merged[-1]["class"] == "EQUIPMENT_FAULT" and
                set(curr["tractors"]) == set(merged[-1]["tractors"])):
            prev = merged[-1]
            gap = (pd.Timestamp(curr["start"]) - pd.Timestamp(prev["end"])).total_seconds() / 60
            if gap <= 18:
                prev["end"] = max(prev["end"], curr["end"])
                prev["evidence"] = list(dict.fromkeys(prev["evidence"] + curr["evidence"]))
                prev["confidence"] = min(prev["confidence"], curr["confidence"])
                continue
        merged.append(curr)
    return sorted(merged, key=lambda d: d["start"])


def wide_features(df, columns):
    wide = df.pivot(index="ts", columns="tractor_id", values=list(columns)).sort_index()
    for name in columns:
        missing = set(TR) - set(wide[name].columns)
        if missing:
            raise ValueError(f"Missing tractor(s) for {name}: {sorted(missing)}")
    return wide


def persistent_faults(frame):
    w = wide_features(frame, ["mean_cn0", "mean_sats", "link_ok_rate"])
    results = []
    for tractor in TR:
        peers = [t for t in TR if t != tractor]
        own_cn0, peer_cn0 = w["mean_cn0"][tractor], w["mean_cn0"][peers].mean(axis=1)
        own_sats, peer_sats = w["mean_sats"][tractor], w["mean_sats"][peers].mean(axis=1)
        own_link = w["link_ok_rate"][tractor]
        raw = ((peer_cn0 - own_cn0 >= .55) & (peer_sats - own_sats >= .25) &
               (peer_cn0 >= 42) & (own_link >= .95)).fillna(False)
        mask = (raw.astype(float).rolling(21, center=True, min_periods=11)
                .mean() >= .50).fillna(False)
        for start, end in segments(mask):
            if (end - start).total_seconds() / 60 < 30:
                continue
            valid = (w.index >= start) & (w.index < end)
            gap_cn0 = (peer_cn0 - own_cn0)[valid].mean()
            gap_sats = (peer_sats - own_sats)[valid].mean()
            results.append(record("EQUIPMENT_FAULT", start, end, [tractor], [
                f"{tractor}: sustained receiver degradation from {start.isoformat()} to {end.isoformat()}",
                f"Mean C/N0 deficit versus peers: {gap_cn0:.2f} dB-Hz",
                f"Mean satellite-count deficit versus peers: {gap_sats:.2f}",
                "Correction link remained mostly healthy; machine-specific antenna or receiver issue suspected.",
            ], .55))
    return results


def bool_rfi(series):
    """Avoid casting string 'False' to True or pandas future downcasting warnings."""
    return series.map(lambda v: str(v).strip().lower() in ("true", "1", "yes"))


def supplemental_jamming(frame):
    w = wide_features(frame, ["mean_cn0", "mean_sats", "rtk_fixed_rate", "recent_rfi_report"])
    c, s = w["mean_cn0"], w["mean_sats"]
    rfi = w["recent_rfi_report"].apply(bool_rfi)
    severe = ((c < 27) & (s < 9)).sum(axis=1) >= 2
    weak = (c < 41) & c.rsub(c.max(axis=1), axis=0).ge(2)
    localized = (weak.sum(axis=1) >= 2) & rfi.any(axis=1)
    results = []
    for mask, kind in ((severe, "severe"), (localized, "localized")):
        smooth = (mask.astype(float).rolling(7, center=True, min_periods=4)
                  .mean() >= .60).fillna(False)
        for start, end in segments(smooth):
            if (end - start).total_seconds() / 60 < 12:
                continue
            period = (w.index >= start) & (w.index < end)
            if kind == "severe":
                affected = [t for t in TR if ((c.loc[period, t] < 27) &
                           (s.loc[period, t] < 9)).mean() >= .5]
            else:
                affected = [t for t in TR if weak.loc[period, t].mean() >= .5]
            if len(affected) < 2:
                continue
            evidence = [
                f"Sustained multi-tractor GNSS signal degradation: {start.isoformat()}–{end.isoformat()}",
                f"Detection pattern: {kind}",
                f"Average affected-tractor C/N0: {c.loc[period, affected].mean().mean():.2f} dB-Hz",
                f"Affected tractors: {', '.join(affected)}",
            ]
            if kind == "localized":
                evidence.append("Recent RFI report supports suspected interference; reports may be delayed or false.")
            else:
                evidence.append("Severe C/N0 and satellite loss; concurrent space weather remains possible.")
            results.append(record("JAMMING", start, end, affected, evidence,
                                  .65 if kind == "severe" else .55))
    return results


def peer_relative_spoofing(frame):
    w = wide_features(frame, ["mean_error", "mean_cn0", "rtk_fixed_rate"])
    results = []
    for tractor in TR:
        peers = [t for t in TR if t != tractor]
        own_error = w["mean_error"][tractor]
        excess = own_error - w["mean_error"][peers].median(axis=1)
        raw = ((excess >= .45) & (own_error >= .65)).fillna(False)
        smooth = (raw.astype(float).rolling(7, center=True, min_periods=4)
                  .mean() >= .60).fillna(False)
        for start, end in segments(smooth):
            if (end - start).total_seconds() / 60 < 8:
                continue
            period = (w.index >= start) & (w.index < end)
            results.append(record("SPOOFING", start, end, [tractor], [
                f"{tractor}: sustained guidance deviation {start.isoformat()} to {end.isoformat()}",
                f"Mean guidance error: {own_error[period].mean():.2f} m",
                f"Mean error excess relative to peers: {excess[period].mean():.2f} m",
                "Peer-relative deviation raises a position-integrity concern; spoofing is suspected, not proven.",
            ], .60))
    return results


def dedup_spoofing(detections):
    spoof = [d for d in detections if d["class"] == "SPOOFING" and len(d["tractors"]) == 1]
    other = [d for d in detections if not (d["class"] == "SPOOFING" and len(d["tractors"]) == 1)]
    merged = []
    for tractor in TR:
        for item in sorted((d for d in spoof if d["tractors"] == [tractor]),
                           key=lambda d: d["start"]):
            if merged and merged[-1]["tractors"] == [tractor]:
                prev = merged[-1]
                if pd.Timestamp(item["start"]) <= pd.Timestamp(prev["end"]):
                    prev["end"] = max(prev["end"], item["end"])
                    prev["confidence"] = max(prev["confidence"], item["confidence"])
                    prev["evidence"] = list(dict.fromkeys(prev["evidence"] + item["evidence"]))
                    continue
            merged.append({**item, "evidence": list(item["evidence"])})
    return sorted(other + merged, key=lambda d: d["start"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mode", choices=WINDOWS, default="evaluation")
    parser.add_argument("--features", default="fused_features.csv")
    parser.add_argument("--output", default=None)
    parser.add_argument("--github-handle", default="shiyalisaravanan-17")
    parser.add_argument("--repo-url", default="https://github.com/shiyalisaravanan-17/project_bali_papa")
    args = parser.parse_args()
    start, end = (pd.Timestamp(v) for v in WINDOWS[args.mode])
    output = args.output or ("submission.json" if args.mode == "evaluation" else "integrated_development.json")
    df = pd.read_csv(args.features, parse_dates=["ts"])
    df["ts"] = pd.to_datetime(df["ts"], utc=True)
    df = df[(df.ts >= start) & (df.ts < end)].sort_values(["ts", "tractor_id"]).copy()
    if df.empty:
        raise ValueError(f"No feature rows in {args.mode} window {start}–{end}")
    required = {"tractor_id", "mean_cn0", "min_sats", "mean_sats", "mean_error", "max_error",
                "rtk_fixed_rate", "link_ok_rate", "s4", "kp", "dst_nT", "affected_fleet_count",
                "recent_rfi_report"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"Missing feature columns: {sorted(missing)}")
    if df.duplicated(["ts", "tractor_id"]).any():
        raise ValueError("Duplicate tractor-minute feature timestamps")

    detections = base_detections(df, end)
    print(f"Base detections: {len(detections)}")
    detections = group_fleet(detections)
    print(f"After fleet grouping: {len(detections)}")
    detections = merge_faults(detections)
    print(f"After equipment fault merging: {len(detections)}")
    new_faults = persistent_faults(df)
    detections.extend(new_faults)
    print(f"Additional persistent faults: {len(new_faults)}")
    new_jamming = supplemental_jamming(df)
    detections.extend(new_jamming)
    print(f"Additional jamming events: {len(new_jamming)}")
    new_spoofing = peer_relative_spoofing(df)
    detections.extend(new_spoofing)
    print(f"Additional peer-relative spoofing events: {len(new_spoofing)}")
    detections = dedup_spoofing(detections)
    print(f"After spoofing deduplication: {len(detections)}")

    # Guard against edges and invalid durations in a scored-window submission.
    valid = []
    for d in detections:
        a, b = pd.Timestamp(d["start"]), pd.Timestamp(d["end"])
        if a < start or a >= end or b <= a or b > end:
            raise ValueError(f"Detection outside {args.mode} window: {d}")
        valid.append(d)
    output_obj = {"participant": {"github_handle": args.github_handle},
                  "repository_url": args.repo_url, "detections": valid}
    Path(output).write_text(json.dumps(output_obj, indent=2), encoding="utf-8")
    print(f"Saved {output} ({len(valid)} detections; {args.mode} window)")
    print(pd.Series([d["class"] for d in valid]).value_counts().to_string() if valid else "No detections")
    if not valid:
        print("WARNING: No detections; official submission requires a nonempty detections list.")
    if args.mode == "development":
        print("Compare integrated_development.json with best_development_so_far.json BEFORE trusting equivalence.")
    else:
        print("Validate: python submission/validate_submission.py submission.json")


if __name__ == "__main__":
    main()
